export type Route = "urgent" | "normal";

/**
 * 受信した瞬間に「緊急ルートに回すか」を決めるための粗いキーワード判定。
 * ここで決めるのは処理の順番だけで、緊急通知するかどうかの最終判断は必ず Claude が行う。
 * そのため「拾いすぎ」は問題にならず（すぐ処理されるだけ）、「取りこぼし」だけが遅延につながる。
 * → 語幹で広めに拾う。漏れたクレームも通常ルート（1分ごとのCron）で拾われるので、SLA 5分には収まる。
 */
const URGENT_PATTERNS: RegExp[] = [
  /クレーム|苦情|抗議|申し入れ/,
  /至急|緊急|大至急|すぐに?対応|早急/,
  /故障|壊れ|不具合|動か|動きませ|効か|効きませ|つかな|つきませ|出な|出ませ/,
  /水漏れ|漏水|雨漏り|浸水|断水|停電|ガス|異臭|火事|火災|煙/,
  /鍵|閉じ込め|開かな|開きませ/,
  /騒音|うるさ/,
  /返金|弁護士|訴え|消費者センター|説明と違|話が違|違いすぎ|ひどい|最悪|責任/,
];

export function detectRoute(text: string): Route {
  return URGENT_PATTERNS.some((pattern) => pattern.test(text)) ? "urgent" : "normal";
}
